const MISREADING_RE = new RegExp(MISREADINGS.map(([w]) => w.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')).join('|'), 'g');
const MISREADING_MAP = new Map(MISREADINGS);

/** 読み違いを直す（文字列以外はそのまま返す） */
function fixMisreadings(text) {
  if (typeof text !== 'string' || !text) return text;
  // 読み違いが重なる（「陵上自衛隧」）と1回では片方しか直らないため、変わらなくなるまで繰り返す
  let t = text;
  for (let i = 0; i < 3; i++) {
    const next = t.replace(MISREADING_RE, (m) => MISREADING_MAP.get(m) || m).replace(ERA_MISREAD_RE, '令和');
    if (next === t) break;
    t = next;
  }
  return t;
}

/** LLM のプロンプトに入れる辞書の文面 */
